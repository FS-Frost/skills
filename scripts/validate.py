#!/usr/bin/env python3
"""Validates the repo's skills and keeps AGENTS.md in sync.

Usage:
    python3 scripts/validate.py               # validate; fails if AGENTS.md is stale
    python3 scripts/validate.py --fix-agents  # also regenerate AGENTS.md

Per-skill checks (skills/<folder>/SKILL.md):
  - The YAML frontmatter parses (minimal parser, no dependencies).
  - `name` exists and matches the folder name (kebab-case).
  - `description` exists, is non-empty, <= 1024 characters, and states when to use it.
  - Relative files referenced from SKILL.md exist.
Global check:
  - AGENTS.md matches what the frontmatters generate.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SKILLS_DIR = REPO / "skills"
AGENTS_MD = REPO / "AGENTS.md"

MAX_DESCRIPTION = 1024
KEBAB_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
# The description must state WHEN to use the skill, not just what it is.
# Markers cover both Spanish and English descriptions.
WHEN_MARKERS = (
    "cuando",
    "cuándo",
    "úsala",
    "úsalo",
    "usa ",
    "when",
    "use it",
    "triggers",
)


def parse_frontmatter(text: str) -> dict[str, str] | None:
    """Minimal parser for flat YAML frontmatter (key: value, with indented continuations)."""
    if not text.startswith("---\n"):
        return None
    end = text.find("\n---", 4)
    if end == -1:
        return None
    block = text[4:end]
    data: dict[str, str] = {}
    current_key = None
    for line in block.splitlines():
        if not line.strip():
            continue
        if line[0] in (" ", "\t") and current_key:
            data[current_key] += " " + line.strip()
            continue
        if ":" not in line:
            return None
        key, _, value = line.partition(":")
        current_key = key.strip()
        data[current_key] = value.strip().strip('"').strip("'")
    return data


def referenced_paths(text: str) -> list[str]:
    """Relative paths referenced: markdown links and mentions of reference/ or scripts/."""
    paths = []
    for match in re.finditer(r"\]\(([^)]+)\)", text):
        target = match.group(1)
        if target.startswith(("http://", "https://", "#", "mailto:")):
            continue
        paths.append(target.split("#")[0])
    for match in re.finditer(r"`((?:reference|scripts)/[^`]+)`", text):
        paths.append(match.group(1))
    return paths


def validate_skill(skill_dir: Path, errors: list[str]) -> dict[str, str] | None:
    skill_md = skill_dir / "SKILL.md"
    label = skill_dir.relative_to(REPO)
    if not skill_md.is_file():
        errors.append(f"{label}: missing SKILL.md")
        return None
    text = skill_md.read_text(encoding="utf-8")
    fm = parse_frontmatter(text)
    if fm is None:
        errors.append(f"{label}: frontmatter missing or does not parse")
        return None

    name = fm.get("name", "")
    if not name:
        errors.append(f"{label}: frontmatter has no `name`")
    elif name != skill_dir.name:
        errors.append(f"{label}: name `{name}` != folder `{skill_dir.name}`")
    elif not KEBAB_RE.match(name):
        errors.append(f"{label}: name `{name}` is not kebab-case")

    description = fm.get("description", "")
    if not description:
        errors.append(f"{label}: frontmatter has no `description`")
    else:
        if len(description) > MAX_DESCRIPTION:
            errors.append(
                f"{label}: description is {len(description)} chars (max {MAX_DESCRIPTION})"
            )
        if not any(marker in description.lower() for marker in WHEN_MARKERS):
            errors.append(
                f"{label}: description does not state when to use it "
                f"(expected one of: {', '.join(WHEN_MARKERS)})"
            )

    for rel in referenced_paths(text):
        if not (skill_dir / rel).exists():
            errors.append(f"{label}: broken reference `{rel}`")

    return fm


def render_agents_md(skills: list[dict[str, str]]) -> str:
    lines = [
        "# Skills index",
        "",
        "Generated by `scripts/validate.py --fix-agents`. Do not edit by hand.",
        "",
        "| Skill | Description |",
        "|---|---|",
    ]
    for fm in sorted(skills, key=lambda s: s["name"]):
        desc = fm["description"].replace("|", "\\|")
        lines.append(f"| [{fm['name']}](skills/{fm['name']}/SKILL.md) | {desc} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    fix_agents = "--fix-agents" in sys.argv
    errors: list[str] = []

    if not SKILLS_DIR.is_dir():
        print("ERROR: skills/ does not exist", file=sys.stderr)
        return 1

    skill_dirs = sorted(p for p in SKILLS_DIR.iterdir() if p.is_dir())
    if not skill_dirs:
        errors.append("skills/: no skills found")

    frontmatters = []
    for skill_dir in skill_dirs:
        fm = validate_skill(skill_dir, errors)
        if fm and fm.get("name") and fm.get("description"):
            frontmatters.append(fm)

    expected = render_agents_md(frontmatters)
    if fix_agents:
        AGENTS_MD.write_text(expected, encoding="utf-8")
        print(f"✓ AGENTS.md regenerated ({len(frontmatters)} skills)")
    elif not AGENTS_MD.is_file():
        errors.append("AGENTS.md does not exist — run `python3 scripts/validate.py --fix-agents`")
    elif AGENTS_MD.read_text(encoding="utf-8") != expected:
        errors.append("AGENTS.md is stale — run `python3 scripts/validate.py --fix-agents`")

    if errors:
        for err in errors:
            print(f"✗ {err}", file=sys.stderr)
        return 1

    print(f"✓ {len(frontmatters)} valid skill(s), AGENTS.md up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
