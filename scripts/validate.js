#!/usr/bin/env node
// Validates the repo's skills and keeps AGENTS.md in sync.
//
// Usage:
//   node scripts/validate.js               # validate; fails if AGENTS.md is stale
//   node scripts/validate.js --fix-agents  # also regenerate AGENTS.md
//
// Per-skill checks (skills/<folder>/SKILL.md):
//   - The YAML frontmatter parses (minimal parser, no dependencies).
//   - `name` exists and matches the folder name (kebab-case).
//   - `description` exists, is non-empty, <= 1024 characters, and states when to use it.
//   - Relative files referenced from SKILL.md exist.
// Global check:
//   - AGENTS.md matches what the frontmatters generate.
"use strict";

const fs = require("fs");
const path = require("path");

const REPO = path.resolve(__dirname, "..");
const SKILLS_DIR = path.join(REPO, "skills");
const AGENTS_MD = path.join(REPO, "AGENTS.md");

const MAX_DESCRIPTION = 1024;
const KEBAB_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const WHEN_MARKERS = [
  "cuando",
  "cuándo",
  "úsala",
  "úsalo",
  "usa ",
  "when",
  "use it",
  "triggers",
];

function parseFrontmatter(rawText) {
  const text = rawText.replace(/\r\n/g, "\n");
  if (!text.startsWith("---\n")) return null;
  const end = text.indexOf("\n---", 4);
  if (end === -1) return null;
  const block = text.slice(4, end);
  const data = {};
  let currentKey = null;
  for (const line of block.split("\n")) {
    if (!line.trim()) continue;
    if ((line[0] === " " || line[0] === "\t") && currentKey) {
      data[currentKey] += " " + line.trim();
      continue;
    }
    if (!line.includes(":")) return null;
    const idx = line.indexOf(":");
    currentKey = line.slice(0, idx).trim();
    data[currentKey] = line
      .slice(idx + 1)
      .trim()
      .replace(/^['"]|['"]$/g, "");
  }
  return data;
}

function referencedPaths(text) {
  const paths = [];
  const linkRe = /\]\(([^)]+)\)/g;
  let m;
  while ((m = linkRe.exec(text)) !== null) {
    const target = m[1];
    if (/^(https?:\/\/|#|mailto:)/.test(target)) continue;
    paths.push(target.split("#")[0]);
  }
  const codeRe = /`((?:reference|scripts)\/[^`]+)`/g;
  while ((m = codeRe.exec(text)) !== null) {
    paths.push(m[1]);
  }
  return paths;
}

function validateSkill(skillDir, errors) {
  const skillMd = path.join(skillDir, "SKILL.md");
  const label = path.relative(REPO, skillDir);
  if (!fs.existsSync(skillMd)) {
    errors.push(`${label}: missing SKILL.md`);
    return null;
  }
  const text = fs.readFileSync(skillMd, "utf8");
  const fm = parseFrontmatter(text);
  if (fm === null) {
    errors.push(`${label}: frontmatter missing or does not parse`);
    return null;
  }

  const name = fm.name || "";
  const dirName = path.basename(skillDir);
  if (!name) {
    errors.push(`${label}: frontmatter has no \`name\``);
  } else if (name !== dirName) {
    errors.push(`${label}: name \`${name}\` != folder \`${dirName}\``);
  } else if (!KEBAB_RE.test(name)) {
    errors.push(`${label}: name \`${name}\` is not kebab-case`);
  }

  const description = fm.description || "";
  if (!description) {
    errors.push(`${label}: frontmatter has no \`description\``);
  } else {
    if (description.length > MAX_DESCRIPTION) {
      errors.push(
        `${label}: description is ${description.length} chars (max ${MAX_DESCRIPTION})`
      );
    }
    const lower = description.toLowerCase();
    if (!WHEN_MARKERS.some((marker) => lower.includes(marker))) {
      errors.push(
        `${label}: description does not state when to use it ` +
          `(expected one of: ${WHEN_MARKERS.join(", ")})`
      );
    }
  }

  for (const rel of referencedPaths(text)) {
    if (!fs.existsSync(path.join(skillDir, rel))) {
      errors.push(`${label}: broken reference \`${rel}\``);
    }
  }

  return fm;
}

function renderAgentsMd(skills) {
  const lines = [
    "# Skills index",
    "",
    "Generated by `scripts/validate.js --fix-agents`. Do not edit by hand.",
    "",
    "| Skill | Description |",
    "|---|---|",
  ];
  const sorted = [...skills].sort((a, b) => a.name.localeCompare(b.name));
  for (const fm of sorted) {
    const desc = fm.description.replace(/\|/g, "\\|");
    lines.push(`| [${fm.name}](skills/${fm.name}/SKILL.md) | ${desc} |`);
  }
  lines.push("");
  return lines.join("\n");
}

function main() {
  const fixAgents = process.argv.includes("--fix-agents");
  const errors = [];

  if (!fs.existsSync(SKILLS_DIR)) {
    console.error("ERROR: skills/ does not exist");
    process.exit(1);
  }

  const skillDirs = fs
    .readdirSync(SKILLS_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => path.join(SKILLS_DIR, d.name))
    .sort();

  if (skillDirs.length === 0) {
    errors.push("skills/: no skills found");
  }

  const frontmatters = [];
  for (const skillDir of skillDirs) {
    const fm = validateSkill(skillDir, errors);
    if (fm && fm.name && fm.description) {
      frontmatters.push(fm);
    }
  }

  const expected = renderAgentsMd(frontmatters);
  if (fixAgents) {
    fs.writeFileSync(AGENTS_MD, expected, "utf8");
    console.log(`✓ AGENTS.md regenerated (${frontmatters.length} skills)`);
  } else if (!fs.existsSync(AGENTS_MD)) {
    errors.push(
      "AGENTS.md does not exist — run `node scripts/validate.js --fix-agents`"
    );
  } else if (fs.readFileSync(AGENTS_MD, "utf8").replace(/\r\n/g, "\n") !== expected) {
    errors.push(
      "AGENTS.md is stale — run `node scripts/validate.js --fix-agents`"
    );
  }

  if (errors.length > 0) {
    for (const err of errors) {
      console.error(`✗ ${err}`);
    }
    process.exit(1);
  }

  console.log(
    `✓ ${frontmatters.length} valid skill(s), AGENTS.md up to date`
  );
}

main();
